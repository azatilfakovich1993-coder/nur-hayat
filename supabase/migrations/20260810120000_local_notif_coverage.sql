-- Телефон планирует "Аят дня" и азкары локально на 30 дней вперёд, но сервер
-- об этом не знал и слал свой push в то же самое локальное время — на Android
-- каждое такое уведомление приходило дважды.
--
-- Здесь телефон отмечает, по какую дату (его локальную) уже стоят локальные
-- будильники. Сервер до этой даты на android-токены не шлёт, а web/iOS
-- обслуживает как раньше. Тот же приём, что уже работает для намаза через
-- prayer_schedules.local_scheduled_date, но там покрытие однодневное, а тут
-- диапазон — локальные уведомления ставятся сразу на месяц вперёд.
alter table prayer_schedules
  add column if not exists daily_verse_local_until date,
  add column if not exists azkar_local_until       date;
